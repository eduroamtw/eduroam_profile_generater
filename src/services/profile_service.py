"""
Profile generation service.
"""

from pathlib import Path

from src.domain import ProfileConfig, ProfileGenerationError
from src.infrastructure import FileRepository


class ProfileService:
    """Service for generating eduroam profiles."""

    def __init__(
        self,
        file_repo: FileRepository,
        template_dir: Path,
        profile_dir: Path,
    ):
        self.file_repo = file_repo
        self.template_dir = template_dir
        self.profile_dir = profile_dir

    def generate_profile(self, config: ProfileConfig) -> str:
        """
        Generate eduroam profile configuration file.

        Args:
            config: Profile configuration

        Returns:
            Generated profile filename

        Raises:
            ProfileGenerationError: If profile generation fails
        """
        # Select template based on supported methods
        template_file = self._select_template(config)

        # Read template
        template_path = self.template_dir / template_file
        if not self.file_repo.exists(template_path):
            raise ProfileGenerationError(f"Template not found: {template_file}")

        template_content = self.file_repo.read_text(template_path)

        # Replace placeholders
        profile_content = self._replace_placeholders(template_content, config)

        # Write profile file
        profile_filename = f"eduroam-eap-generic-{config.short_name}.eap-config"
        profile_path = self.profile_dir / profile_filename

        self.file_repo.ensure_directory(self.profile_dir)
        self.file_repo.write_text(profile_path, profile_content)

        return profile_filename

    def _select_template(self, config: ProfileConfig) -> str:
        """Select appropriate template based on supported methods."""
        if config.supports_both_methods:
            return "eduroam-eap-generic-anonymous-Both.eap-config"
        elif config.supports_pap_only:
            return "eduroam-eap-generic-anonymous-TTLS-PAP.eap-config"
        elif config.supports_mschapv2_only:
            return "eduroam-eap-generic-anonymous-PEAP-MSCHAPv2.eap-config"
        else:
            raise ProfileGenerationError("No authentication method available")

    def _replace_placeholders(
        self, template_content: str, config: ProfileConfig
    ) -> str:
        """Replace template placeholders with actual values."""
        replacements = {
            "#Realm#": str(config.realm),
            "#PEAP_MSCHAPv2Cert#": config.mschapv2_cert or "",
            "#TTLS_PAPCert#": config.pap_cert or "",
            "#Domain#": config.dns or "",
            "#Name#": f"{config.name} Compatible Profile",
            "#Desc#": f"Profile generated by third party, suitable for accounts with @{config.realm}",
            "#Email#": config.email,
            "#URL#": config.url,
            "#Tel#": "NULL",
        }

        result = template_content
        for placeholder, value in replacements.items():
            result = result.replace(placeholder, value)

        return result
